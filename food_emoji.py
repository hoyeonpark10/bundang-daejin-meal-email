def get_food_emojis(dish_name):
    """메뉴 이름에 어울리는 이모지를 전부 찾아서 리스트로 돌려줍니다."""
    emojis = []
    for emoji, keywords in FOOD_EMOJI_RULES:
        if any(keyword in dish_name for keyword in keywords):
            emojis.append(emoji)
    return emojis
